    """依公司型態補充規模面的攻略。"""
    if is_startup:
        return ("【新創攻略】公司剛設立,正處團隊建立與開幕籌備期:"
                "以「小量客製、快速交件、首購折扣」切入,聯絡時恭喜設立新公司,"
                "詢問開幕日期並主動提供 logo 打樣。")
    if capital >= 100_000_000:
        return ("【中大型攻略】資本額破億,採購多走正式流程:"
                "先寄公司簡介與型錄到公司信箱,電話中詢問「總務/人資/採購」窗口,"
                "以年度制服採購與批量階梯價提案。")
    return ("【中型攻略】公司近期有登記異動(可能增資、遷址或改組),"
            "常伴隨擴編或搬遷開新據點:電話中確認是否擴編,"
            "以「換新識別、全員換裝」提案,提供樣品寄送。")
