# 低價值類別:比對到即大幅降分(通常無實體人力、無制服需求)
LOW_VALUE_KEYWORDS = ["投資", "控股", "創業投資", "資產管理", "不動產買賣",
                      "不動產租賃", "租賃住宅", "管理顧問", "財務顧問"]

DEFAULT_RULE = ("一般企業", [], 10,
                "polo 衫、外套(員工識別)",
                "先以電話確認公司實際營業性質與員工規模,再決定是否寄送型錄。")


def classify(business_items_text: str, company_name: str):
    """回傳 (產業名稱, 權重, 需求品項, 攻略法)。取關鍵字命中最多的規則。"""
    text = (business_items_text or "") + " " + (company_name or "")
    best = None
    best_hits = 0
    for name, keywords, weight, items, pitch in INDUSTRY_RULES:
        hits = sum(1 for kw in keywords if kw in text)
        if hits > best_hits:
            best = (name, weight, items, pitch)
            best_hits = hits
    if best is None:
        name, _, weight, items, pitch = DEFAULT_RULE
        best = (name, weight, items, pitch)
    # 低價值類別降分(僅在沒有強產業訊號時)
    if best_hits <= 1 and any(kw in text for kw in LOW_VALUE_KEYWORDS):
        return ("投資/顧問(低優先)", 3, "-", "此類公司通常無制服需求,建議略過。")
    return best


